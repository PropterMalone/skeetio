"""What the bot decides, tested without a network.

The bot's risky surface is not its HTTP calls, it is its judgements: whether a
mention is a request or a takedown, what a screen reader is told, and — the one
that matters most — which exit codes end a request versus leave it to be tried
again. A code that fell through the wrong branch would either strand a person
with no answer or answer them repeatedly.
"""

