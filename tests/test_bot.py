# --- the exit-code policy ---------------------------------------------------
# The property under test: every documented code lands in exactly one of
# "answer and close", "leave for retry", or "stop the bot" — and none falls
# through to a fourth, undefined behaviour.


PERMANENT = {exits.NO_TEXT, exits.UNRENDERABLE_SCRIPT}
HALT = {exits.BAD_ENV, exits.IDENTITY_MISMATCH}


def test_every_documented_code_has_a_defined_disposition():
    for e in exits.CONTRACT:
        if e.code == exits.OK:
            continue
        assert (
            e.code in PERMANENT
            or exits.is_retryable(e.code)
            or e.code in HALT
            or e.code == exits.EMPTY_POST_TEXT
        ), f"{e.name} ({e.code}) has no disposition — the bot would not know what to do"


def test_permanent_codes_are_answered_rather_than_retried():
    """Someone whose post cannot be rendered gets told once. Retrying a
    permanent failure means never telling them and never stopping."""
    for code in PERMANENT:
        assert not exits.is_retryable(code)


def test_operator_errors_never_look_retryable_to_the_bot():
    """Retrying past IDENTITY_MISMATCH is retrying past the guard that stops the
    bot posting as the wrong account."""
    for code in HALT:
        assert not exits.is_retryable(code)


def test_undocumented_codes_are_the_case_the_bot_must_handle():
    """The real hazard: a crash exits 1, argparse exits 2, a signal gives a
    negative return. None are in the contract, and `code // 10` puts them in no
    group — so the bot cannot dispatch on the tens digit alone and must check
    membership."""
    for code in (1, 2, 3, -9, 99):
        assert code not in exits.BY_CODE
        assert not exits.is_retryable(code) or code // 10 in (2, 4)


def test_fetch_failed_is_retryable_and_transport_shaped():
    """It exists because a network error used to escape as exit 1, which is in
    no group at all."""
    assert exits.FETCH_FAILED in exits.BY_CODE
    assert exits.is_retryable(exits.FETCH_FAILED)


