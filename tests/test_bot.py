# --- what handle() actually does, with the network taken away ---------------
# The branch logic is where the consent properties live: who gets answered, who
# gets refused, and what is written down about it. Driven through handle() end
# to end rather than asserted about its parts.

import ledger  # noqa: E402
from post import Post  # noqa: E402

BOT = "did:plc:bot"
ASKER = "did:plc:asker"
AUTHOR = "did:plc:author"


def _post(uri, did, text="", parent=None, handle="x.bsky.social") -> Post:
    root = {"uri": parent, "cid": "bafyroot"} if parent else None
    return Post(uri=uri, cid="bafy" + uri[-4:], text=text, handle=handle,
                display_name="X", did=did, avatar_url=None, created_at="2026-08-19T00:00:00Z",
                likes=0, reposts=0, replies=0, quotes=0,
                reply_parent_uri=parent, reply_root=root)


class _Opts:
    bot_did = BOT
    bot_handle = "skeetio.bsky.social"
    dry_run = True
    env = "/nonexistent"
    expect_account = None
    dur = 10.0
    generic = False
    limit = 25


@pytest.fixture(autouse=True)
def _isolated(tmp_path, monkeypatch):
    monkeypatch.setattr(ledger, "STATE", tmp_path)
    monkeypatch.setattr(ledger, "LEDGER", tmp_path / "ledger.jsonl")
    # Any real HTTP is a bug in the test, not a slow test.
    monkeypatch.setattr(bot, "_req", lambda *a, **k: pytest.fail("bot made a network call"))


REQ_URI = "at://did:plc:asker/app.bsky.feed.post/req"
SRC_URI = "at://did:plc:author/app.bsky.feed.post/src"


def _note(uri=REQ_URI, did=ASKER):
    return {"uri": uri, "author": {"did": did}}


def test_a_mention_that_is_not_a_reply_is_refused_and_recorded(monkeypatch):
    """There is no post above it to render. The person still gets told, once."""
    monkeypatch.setattr(bot.P, "fetch", lambda u: _post(REQ_URI, ASKER, "@skeetio do it"))
    said = []
    monkeypatch.setattr(bot, "say", lambda req, text, o, t: said.append(text))

    bot.handle(_note(), _Opts(), "token")

    rows = ledger.rows()
    assert [r["outcome"] for r in rows] == ["refused"]
    assert rows[0]["note"] == "not a reply"
    assert said, "the requester was left with no answer at all"


def test_the_bot_never_answers_itself(monkeypatch):
    """Its own posts come back as notifications. Answering them is a loop."""
    monkeypatch.setattr(bot.P, "fetch", lambda u: pytest.fail("should not have fetched"))
    bot.handle(_note(did=BOT), _Opts(), "token")
    assert ledger.rows() == []


def test_an_already_answered_request_is_left_alone(monkeypatch):
    ledger.append(ledger.Row(outcome="posted", request_uri=REQ_URI, requester_did=ASKER,
                             source_uri=SRC_URI, source_did=AUTHOR, at=ledger.now(),
                             reply_uri="at://bot/x"))
    monkeypatch.setattr(bot.P, "fetch", lambda u: pytest.fail("re-read an answered request"))
    bot.handle(_note(), _Opts(), "token")
    assert len(ledger.rows()) == 1, "a second row means it would have posted twice"


def test_a_request_claims_before_it_renders(monkeypatch):
    """The claim has to be on disk *before* the post goes out, or a crash in
    between leaves nothing saying the attempt ever happened."""
    order = []
    monkeypatch.setattr(bot.P, "fetch", lambda u: (
        _post(REQ_URI, ASKER, "@skeetio do it", parent=SRC_URI)
        if u == REQ_URI else _post(SRC_URI, AUTHOR, "words worth rendering")))
    monkeypatch.setattr(bot, "render_and_reply",
                        lambda *a: (order.append(ledger.rows()[-1]["outcome"]), (exits.OK, {}))[1])

    bot.handle(_note(), _Opts(), "token")

    assert order == ["claimed"], "rendering started with no claim written"
    assert [r["outcome"] for r in ledger.rows()] == ["claimed", "posted"]


def test_a_retryable_failure_writes_no_terminal_row(monkeypatch):
    """So the stale claim releases it and the next pass tries again. A terminal
    row here would strand the requester permanently on a transient error."""
    monkeypatch.setattr(bot.P, "fetch", lambda u: (
        _post(REQ_URI, ASKER, "@skeetio do it", parent=SRC_URI)
        if u == REQ_URI else _post(SRC_URI, AUTHOR, "words")))
